CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('student','admin') NOT NULL DEFAULT 'student', roll_no VARCHAR(50) UNIQUE,
 department VARCHAR(100) NOT NULL DEFAULT '', year INT NOT NULL DEFAULT 1,
 token_version INT NOT NULL DEFAULT 0, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(year BETWEEN 1 AND 6)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS clubs (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE,
 description TEXT NOT NULL, admin_id INT UNSIGNED NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, FOREIGN KEY(admin_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS events (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, club_id INT UNSIGNED NOT NULL,
 title VARCHAR(150) NOT NULL, description TEXT NOT NULL, starts_at DATETIME NOT NULL,
 venue VARCHAR(150) NOT NULL, capacity INT NOT NULL, fee_paise INT NOT NULL DEFAULT 0,
 status ENUM('open','closed','cancelled','completed') NOT NULL DEFAULT 'open',
 FOREIGN KEY(club_id) REFERENCES clubs(id), CHECK(capacity BETWEEN 1 AND 10000),CHECK(fee_paise>=0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS memberships (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, club_id INT UNSIGNED NOT NULL, user_id INT UNSIGNED NOT NULL,
 status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY one_membership(club_id,user_id),
 FOREIGN KEY(club_id) REFERENCES clubs(id), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS registrations (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, event_id INT UNSIGNED NOT NULL,user_id INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY one_registration(event_id,user_id),
 FOREIGN KEY(event_id) REFERENCES events(id), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS attendance (
 registration_id INT UNSIGNED PRIMARY KEY, marked_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(registration_id) REFERENCES registrations(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS announcements (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,club_id INT UNSIGNED NOT NULL,
 title VARCHAR(150) NOT NULL,body TEXT NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(club_id) REFERENCES clubs(id)
) ENGINE=InnoDB;
